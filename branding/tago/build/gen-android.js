// Writes the app's launcher icon layers and in-app logo as Android vector drawables, from the
// same geometry as the SVG kit (gen-kit.js). Usage: node gen-android.js
const fs = require('fs');
const path = require('path');
const { C, symbolParts } = require('./gen-kit');

const RES = path.join(__dirname, '..', '..', '..', 'app', 'src', 'main', 'res');
const f = (n) => +n.toFixed(4);

// Adaptive icon layers are 108 x 108 dp; launchers show the middle 72 and guarantee a 66 dp
// circle. The symbol's farthest point (a corner node) is 112.5 units from its centre, so at
// 46 dp across (scale 46/176) it reaches 29.4 dp: inside the 33 dp safe radius.
const SCALE = 46 / 176;
const OFFSET = 54 - 128 * SCALE;

const launcherLayer = (comment, fill, kind) => {
  const p = symbolParts(kind);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${comment}
     Generated by branding/tago/build/gen-android.js from the logo kit's geometry; edit there. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="${f(SCALE)}" android:scaleY="${f(SCALE)}"
        android:translateX="${f(OFFSET)}" android:translateY="${f(OFFSET)}">
        <path android:fillColor="${fill}" android:pathData="${p.body}${p.start}"/>
    </group>
</vector>
`;
};

const files = {
  'drawable/ic_launcher_foreground.xml': launcherLayer(
    'Tago launcher foreground: the T traced on the unlock grid, in paper on the indigo background.\n' +
    '     One colour on purpose: at launcher size a coral start node reads as a notification dot.',
    C.paper, 'reversed'),
  'drawable/ic_launcher_monochrome.xml': launcherLayer(
    'Monochrome layer for Android 13+ themed icons. The launcher tints the shape and uses only\n' +
    '     its alpha, so the colour here does not matter. Same geometry as the foreground.',
    '@android:color/white', 'reversed'),
  'values/ic_launcher_background.xml': `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Tago indigo, the brand colour (also the app's light-theme accent). -->
    <color name="ic_launcher_background">${C.indigo}</color>
</resources>
`,
  // In-app logo: the full-colour symbol, theme-aware (accent is lighter in dark mode).
  'drawable/ic_logo.xml': (() => {
    const p = symbolParts('regular');
    return `<?xml version="1.0" encoding="utf-8"?>
<!-- Tago symbol for in-app use (unlock screen). Accent + coral start node; both colours have
     night values, so it stays visible in dark mode.
     Generated by branding/tago/build/gen-android.js from the logo kit's geometry; edit there. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="72dp" android:height="72dp"
    android:viewportWidth="256" android:viewportHeight="256">
    <path android:fillColor="@color/accent" android:pathData="${p.body}"/>
    <path android:fillColor="@color/action" android:pathData="${p.start}"/>
</vector>
`;
  })(),
};

for (const [rel, content] of Object.entries(files)) {
  fs.writeFileSync(path.join(RES, rel), content);
  console.log('wrote', rel);
}
