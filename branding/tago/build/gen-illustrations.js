// In-app illustrations in the Tago world, written as Android vector drawables (colours are
// @color resources, so they follow dark mode). Usage: node gen-illustrations.js
//
//   ill_onboarding.xml      a field of faint dots where one T is traced: hidden in plain sight.
//                           Used on the welcome screen and the empty vault.
//   avd_onboarding.xml      the same art, with the T drawing itself once (welcome screen only).
//   ill_grid_idle.xml       nine dots, nothing traced: the no-results state.
const fs = require('fs');
const path = require('path');

const RES = path.join(__dirname, '..', '..', '..', 'app', 'src', 'main', 'res');
const f = (n) => +n.toFixed(2);
const circle = (cx, cy, r) =>
  `M${f(cx - r)},${f(cy)}a${r},${r} 0 1,1 ${f(2 * r)},0a${r},${r} 0 1,1 ${f(-2 * r)},0`;
const HEADER = 'Generated by branding/tago/build/gen-illustrations.js; edit there.';

// ------------------------------------------------------------------ onboarding art
// 360 x 300 dp. Dot field: 7 columns x 6 rows, 48 apart. The 3x3 grid at its upper middle
// (x 132/180/228, y 68/116/164) carries the traced T; the welcome card overlaps the bottom.
const W = 360, H = 300, STEP = 48;
const COLS = [36, 84, 132, 180, 228, 276, 324];
const ROWS = [20, 68, 116, 164, 212, 260];
const GX = [132, 180, 228], GY = [68, 116, 164];
const CX = 180, CY = 116;

const inGrid = (x, y) => GX.includes(x) && GY.includes(y);
// Field dots fade with distance from the traced grid, in four steps (fewer paths).
const levels = new Map();
for (const y of ROWS) for (const x of COLS) {
  if (inGrid(x, y)) continue;
  const d = Math.hypot(x - CX, y - CY);
  const alpha = Math.max(0.18, Math.min(0.9, 1.05 - d / 200));
  const step = Math.round(alpha * 4) / 4 || 0.25;
  if (!levels.has(step)) levels.set(step, []);
  levels.get(step).push(circle(x, y, 5));
}

// Same line-to-node ratio as the logo (about 1 : 1.6), so the art reads as the mark.
const TRACE_W = 16, NODE_R = 13, IDLE_R = 8;
const traced = [[132, 68], [180, 68], [228, 68], [180, 116], [180, 164]];
const idle = [[132, 116], [228, 116], [132, 164], [228, 164]];

const art = (traceName) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Tago world: a field of faint dots where one T is traced on its nine-dot grid, the secret
     hidden in plain sight. Coral marks where the trace starts. Colours come from the palette,
     so it re-tints in dark mode. Decorative: its ImageViews are importantForAccessibility="no".
     ${HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${W}dp" android:height="${H}dp"
    android:viewportWidth="${W}" android:viewportHeight="${H}">
${[...levels.entries()].sort((a, b) => a[0] - b[0]).map(([a, ds]) =>
  `    <path android:fillColor="@color/border_strong" android:fillAlpha="${a}"
        android:pathData="${ds.join('')}"/>`).join('\n')}
    <!-- The grid: unused dots, then the trace and its nodes. -->
    <path android:fillColor="@color/accent" android:fillAlpha="0.4"
        android:pathData="${idle.map(([x, y]) => circle(x, y, IDLE_R)).join('')}"/>
    <path android:name="${traceName}" android:strokeColor="@color/accent"
        android:strokeWidth="${TRACE_W}" android:strokeLineCap="round" android:strokeLineJoin="round"
        android:fillColor="#00000000"
        android:pathData="M132,68H228M180,68V164"/>
    <path android:fillColor="@color/accent"
        android:pathData="${traced.slice(1).map(([x, y]) => circle(x, y, NODE_R)).join('')}"/>
    <path android:fillColor="@color/action" android:pathData="${circle(132, 68, NODE_R)}"/>
</vector>
`;

// Animated version: the trace draws from the start node, across, then down (trimPathEnd),
// once, after the welcome card has settled. Content is complete in the static drawable, so
// with animations off (or if the animation never starts) the full T simply shows.
const avd = `<?xml version="1.0" encoding="utf-8"?>
<!-- Welcome screen: the T traces itself once from the coral start node. 700 ms on Material's
     standard curve (a strong ease-out drew most of it in the first frames, so it never read as traced),
     after a 300 ms beat so the art has arrived first. Started from OnboardingActivity only
     when animations are on. ${HEADER} -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:drawable="@drawable/ill_onboarding">
    <target android:name="trace">
        <aapt:attr name="android:animation">
            <!-- The zero-length step hides the trace the moment the animation starts; without
                 it the full T would show during the 300 ms beat, vanish, then draw. -->
            <set android:ordering="together">
                <objectAnimator
                    android:propertyName="trimPathEnd"
                    android:valueFrom="0"
                    android:valueTo="0"
                    android:valueType="floatType"
                    android:duration="0"/>
                <objectAnimator
                    android:propertyName="trimPathEnd"
                    android:valueFrom="0"
                    android:valueTo="1"
                    android:valueType="floatType"
                    android:startOffset="300"
                    android:duration="700"
                    android:interpolator="@android:interpolator/fast_out_slow_in"/>
            </set>
        </aapt:attr>
    </target>
</animated-vector>
`;

// ------------------------------------------------------------------ no-results grid
const idleGrid = `<?xml version="1.0" encoding="utf-8"?>
<!-- No search results: the nine-dot grid with nothing traced, no pattern matched.
     ${HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="48dp" android:height="48dp"
    android:viewportWidth="48" android:viewportHeight="48">
    <path android:fillColor="@color/border_strong"
        android:pathData="${[10, 24, 38].flatMap((y) => [10, 24, 38].map((x) => circle(x, y, 4))).join('')}"/>
</vector>
`;

const files = {
  'drawable/ill_onboarding.xml': art('trace'),
  'drawable/avd_onboarding.xml': avd,
  'drawable/ill_grid_idle.xml': idleGrid,
};
for (const [rel, content] of Object.entries(files)) {
  fs.writeFileSync(path.join(RES, rel), content);
  console.log('wrote', rel);
}

// Preview SVG of the art (light palette) for review outside Android.
const pal = { border_strong: '#D9CCD0', accent: '#5B56A6', action: '#F0623A' };
const svg = art('trace')
  .replace(/<\?xml[^>]*>\n/, '')
  .replace(/<!--[\s\S]*?-->\n/g, '')
  .replace(/<vector[^>]*>/, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">`)
  .replace('</vector>', '</svg>')
  .replace(/android:fillColor="@color\/(\w+)"/g, (_, c) => `fill="${pal[c]}"`)
  .replace(/android:strokeColor="@color\/(\w+)"/g, (_, c) => `stroke="${pal[c]}"`)
  .replace(/android:fillColor="#00000000"/g, 'fill="none"')
  .replace(/android:fillAlpha=/g, 'fill-opacity=')
  .replace(/android:strokeWidth=/g, 'stroke-width=')
  .replace(/android:strokeLineCap=/g, 'stroke-linecap=')
  .replace(/android:strokeLineJoin=/g, 'stroke-linejoin=')
  .replace(/android:name="[^"]*"\s*/g, '')
  .replace(/android:pathData=/g, 'd=');
fs.writeFileSync(path.join(__dirname, 'preview-ill-onboarding.svg'), svg);
console.log('wrote build/preview-ill-onboarding.svg');
